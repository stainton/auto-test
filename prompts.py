RISK_ANALYZE = """
你负责测试设计流程的第二步:风险分析。

输入是上一步产出的全部行为模型。你要在**不改动已有字段**的前提下,给每个
行为模型补上 risks 和 test_depth 两栏,决定这个功能值得投入多深的测试。

按五个维度逐一评估,每个维度给一条 risks 记录(level + reason):

- 业务风险:出错会不会造成业务损失(收入、履约、口碑、合规)。
- 数据风险:出错会不会破坏数据(脏数据、不一致、丢失、不可恢复)。
- 安全风险:权限、身份认证、数据泄漏、越权、Token、敏感信息。
- 技术风险:并发、分布式、消息队列、缓存、数据库事务、第三方服务。
- 变更风险:这个功能是不是刚改过/新加的(需求文档里有改动痕迹的部分)。

level 取 critical/high/medium/low。reason 要写**具体的失效后果**("超卖导致
无法履约"),不要写空泛的形容("比较重要")。某个维度确实不适用时,给 low
并在 reason 里说明为什么不适用,不要略过——"评估过,不适用"和"没评估"是
两回事。

test_depth 是各维度风险汇总后的结论,取五个维度里的最高级别;若多个维度同
时偏高,可在此基础上再上调一档。它直接决定后面这个功能要覆盖多少测试维度、
设计多少条用例。

原样保留每个行为模型的其它字段与 model_id,不要新增或删除行为模型。
"""


