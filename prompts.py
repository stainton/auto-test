from __future__ import annotations

# ---------------------------------------------------------------------------
# 跨节点复用的口径说明
# ---------------------------------------------------------------------------

VERDICT_GUIDE = """
【四种执行结论及其判定顺序】
一条用例执行完只有四种结论,按下列顺序判定,先命中先返回:

1. BLOCKED       —— 用例根本没能执行。前置条件不满足、环境不可用、依赖服务
                    宕机、账号/权限缺失、前序用例失败导致无法开始。
2. FAIL          —— 存在被**明确违反**的断言。只要抓到确凿的错误行为就判
                    FAIL,不因为别的观测点缺失而降级成 INCONCLUSIVE。
3. INCONCLUSIVE  —— 已经执行了,但判不了。required=true 的观测点取不到值或
                    取到的值不可信、数据被污染、异步等待超时无法区分"没发生"
                    与"还没发生"、结果不稳定。
4. PASS          —— 全部断言满足,且所有 required 观测点都真的取到了值。

BLOCKED 与 INCONCLUSIVE **不是缺陷**,它们暴露的是测试能力的缺口(环境、
数据、可观测性),后续由缺陷分析节点单独归档。

最重要的一条纪律:**没有取到观测值,就不准判 PASS。** 判 PASS 的前提是你
真的看到了预期的现象,而不是"按需求推理它应该会通过"。推理出来的 PASS 是
这套流程里最有害的产物——它会让一个从未被验证过的功能带着"已通过"的标记
进入发布决策。
"""

OBSERVATION_GUIDE = """
【观测点(observations)】
观测点描述"在哪个通道、对哪个对象、用什么方式、在什么时刻"取值。可用通道:
api_response / database / cache / mq / log / third_party / ui / metrics / file。

设计观测点时,除了接口返回值,必须覆盖行为模型里的 `state_transitions`、
`data_changes`、`side_effects`——这三样正是"接口返回成功但系统其实错了"
这类缺陷的藏身处。

几条硬约定:
- 一个观测点只观测一件事,便于断言定位到具体哪里不对。
- required=true 表示"取不到这个值就无法判定本用例",直接决定 INCONCLUSIVE。
- 异步副作用必须在 timing 里写清等待窗口(如 eventually_within_5s),否则
  区分不了"没发生"和"还没发生"。
- **负向观测同样要写**:期望"不发生"的事(不发消息、不扣款、不落库)必须有
  对应观测点,配 absent 断言。少了它,一条只检查返回码的用例会放过重复扣款
  这种最贵的缺陷。
"""

ORACLE_GUIDE = """
【判定准则(oracle)】
oracle = 断言集合 + 本用例特有的判定补充。

- assertions:每条断言绑定一个 observation_id,写清 rule / expected /
  severity,并在 rationale 里指出它对应哪条业务规则或哪个风险点。断言的
  expected 写具体的值或形态,不要写"符合预期"这种没有信息量的话。
- verdict_rules:通用判定顺序(上面那四条)是全流程约定,**不要在这里复述**;
  这四个字段只写本用例**特有**的补充条件,例如"库存表被其它用例并发改动时
  判 INCONCLUSIVE"。确实没有特有补充时写空字符串。

只有 expected_result 而没有 observation 的用例是不可执行的(执行者不知道去
哪个通道取值);只有 observation 而没有 oracle 的用例是不可判定的(取到值也
不知道算通过还是失败)。两者缺一,这条用例就是废的。
"""


