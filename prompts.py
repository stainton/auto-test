SCENARIO_DESIGN = """
你负责测试设计流程的第四步:场景设计。

输入是补齐了风险与测试维度的全部行为模型。你要把这些**单点的行为模型组合
成真实的用户行为**——用户不会只调一个接口就停下,缺陷往往就藏在两个功能的
接缝处(前一步留下的状态、并发窗口、数据在多个功能之间的流转)。

每个场景填:
- scenario_id:   稳定可读的标识,同一次运行内不得重复。
- scenario_name: 用一句用户视角的话概括,而不是接口名的拼接。
- model_ids:     这个场景串起了哪几个行为模型。
- user_journey:  真实的行为序列,一步一句,按用户实际会做的顺序写。
- test_dimensions:这个场景要打的测试维度(来自各行为模型的 test_dimensions)。
- risk_focus:    这个场景对准的是哪个风险——写清"这个场景想抓的是什么缺陷"。
- priority:      critical/high/medium/low,由涉及的行为模型的 test_depth 与
                 该场景在真实使用中的频次共同决定。

纪律:
1. 场景必须是**真实会发生的**行为组合,不要为了凑覆盖率拼接用户根本不会走
   的路径。
2. 高风险的行为模型要同时出现在正常场景与异常场景里(中途失败、中途放弃、
   重复操作、并发操作)——只测顺利路径等于没测。
3. 每个行为模型至少被一个场景覆盖到;某个模型确实无法组合进任何真实场景时,
   单独为它建一个单功能场景,不要让它落空。
"""


